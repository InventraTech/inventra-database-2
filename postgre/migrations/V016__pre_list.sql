-- ---------------------------------------------------
-- PRE-LIST (PRÉ-LISTA DE COMPRA)
-- ---------------------------------------------------
-- Pré-lista de compra herdada do banco do 1º ano (pre_lista e item_pre_lista): um cabeçalho com a data
-- da lista e N itens, cada um com produto, fornecedor e quantidade. É uma lista de intenção de compra,
-- ainda sem estoque nem requisição; para virar compra, o RPA (ou a API) gera uma tb_requisition do tipo
-- PURCHASE com os itens da lista.

-- ---------------------------------------------------
-- TABLE CREATION
-- ---------------------------------------------------

CREATE TABLE IF NOT EXISTS tb_pre_list (
	id_pre_list INTEGER GENERATED BY DEFAULT AS IDENTITY,
	list_date DATE NOT NULL DEFAULT CURRENT_DATE,
	PRIMARY KEY (id_pre_list)
);

CREATE TABLE IF NOT EXISTS tb_pre_list_item (
	id_pre_list_item INTEGER GENERATED BY DEFAULT AS IDENTITY,
	id_pre_list INTEGER NOT NULL,
	id_supplier INTEGER NOT NULL,
	id_product INTEGER NOT NULL,
	quantity DECIMAL(12,3) NOT NULL,
	PRIMARY KEY (id_pre_list_item)
);

-- ---------------------------------------------------
-- FOREIGN KEYS
-- ---------------------------------------------------

DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_prelistitem_prelist') THEN
		ALTER TABLE tb_pre_list_item
		ADD CONSTRAINT fk_prelistitem_prelist
		FOREIGN KEY (id_pre_list) REFERENCES tb_pre_list (id_pre_list)
		ON UPDATE NO ACTION ON DELETE NO ACTION;
	END IF;
END;
$$;

DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_prelistitem_supplier') THEN
		ALTER TABLE tb_pre_list_item
		ADD CONSTRAINT fk_prelistitem_supplier
		FOREIGN KEY (id_supplier) REFERENCES tb_supplier (id_supplier)
		ON UPDATE NO ACTION ON DELETE NO ACTION;
	END IF;
END;
$$;

DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_prelistitem_product') THEN
		ALTER TABLE tb_pre_list_item
		ADD CONSTRAINT fk_prelistitem_product
		FOREIGN KEY (id_product) REFERENCES tb_product (id_product)
		ON UPDATE NO ACTION ON DELETE NO ACTION;
	END IF;
END;
$$;

-- ---------------------------------------------------
-- CHECK CONSTRAINTS
-- ---------------------------------------------------

DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_prelistitem_quantity') THEN
		ALTER TABLE tb_pre_list_item
		ADD CONSTRAINT ck_prelistitem_quantity
		CHECK (quantity > 0);
	END IF;
END;
$$;

-- ---------------------------------------------------
-- INDEX CREATION
-- ---------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_prelist_list_date
ON tb_pre_list (list_date);

CREATE INDEX IF NOT EXISTS idx_prelistitem_prelist
ON tb_pre_list_item (id_pre_list);

CREATE INDEX IF NOT EXISTS idx_prelistitem_supplier
ON tb_pre_list_item (id_supplier);

CREATE INDEX IF NOT EXISTS idx_prelistitem_product
ON tb_pre_list_item (id_product);

-- ---------------------------------------------------
-- PRE-LIST METADATA (V016)
-- ---------------------------------------------------

INSERT INTO tb_catalog_table (table_name, domain, description, business_rules, id_access_level, data_owner)
SELECT v.table_name, v.domain, v.description, v.business_rules, al.id_access_level, v.data_owner
FROM (VALUES
	('tb_pre_list', 'TRANSACTION',
	 'Pré-listas de compra: cabeçalho com a data da lista.',
	 'Uma pré-lista tem N itens (1:N). É intenção de compra: não mexe em estoque nem vira requisição sozinha.',
	 'INTERNAL', 'Compras'),
	('tb_pre_list_item', 'TRANSACTION',
	 'Itens (produto, fornecedor e quantidade) de cada pré-lista.',
	 'Cada item aponta para um produto e um fornecedor cadastrados. Quantidade maior que zero (ck_prelistitem_quantity).',
	 'INTERNAL', 'Compras')
) AS v(table_name, domain, description, business_rules, access_code, data_owner)
JOIN tb_catalog_access_level al ON al.code = v.access_code
ON CONFLICT (table_name) DO UPDATE
SET domain = EXCLUDED.domain,
    description = EXCLUDED.description,
    business_rules = EXCLUDED.business_rules,
    id_access_level = EXCLUDED.id_access_level,
    data_owner = EXCLUDED.data_owner,
    updated_at = CURRENT_TIMESTAMP;

INSERT INTO tb_catalog_column (id_catalog_table, column_name, description, business_rule, id_access_level, is_personal_data)
SELECT t.id_catalog_table, v.column_name, v.description, v.business_rule, NULL, v.is_personal_data
FROM (VALUES
	('tb_pre_list', 'id_pre_list', 'Identificador da pré-lista.', NULL, false),
	('tb_pre_list', 'list_date', 'Data da pré-lista.', 'Padrão: data de hoje.', false),
	('tb_pre_list_item', 'id_pre_list_item', 'Identificador do item.', NULL, false),
	('tb_pre_list_item', 'id_pre_list', 'Pré-lista a que o item pertence.', NULL, false),
	('tb_pre_list_item', 'id_supplier', 'Fornecedor do item.', NULL, false),
	('tb_pre_list_item', 'id_product', 'Produto a comprar.', NULL, false),
	('tb_pre_list_item', 'quantity', 'Quantidade a comprar.', 'Maior que zero (ck_prelistitem_quantity).', false)
) AS v(table_name, column_name, description, business_rule, is_personal_data)
JOIN tb_catalog_table t ON t.table_name = v.table_name
ON CONFLICT (id_catalog_table, column_name) DO UPDATE
SET description = EXCLUDED.description,
    business_rule = EXCLUDED.business_rule,
    id_access_level = EXCLUDED.id_access_level,
    is_personal_data = EXCLUDED.is_personal_data,
    updated_at = CURRENT_TIMESTAMP;

CALL sp_sync_data_catalog();
